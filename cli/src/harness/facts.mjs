// What the kit knows about each built-in harness (ADRs 0028 and 0030), and the
// two preflight rules read from it.
//
// `cli/harnesses.json` is built here from the adapters and the Support Level
// table, written by `node scripts/gen_harnesses.mjs` and held equal to them by
// a contract test. It ships with every kit tag and npm package. Its shape can
// only grow: a field may be added, and is never renamed or removed, because an
// older CLI reads a newer tag's file and a newer CLI an older one.

import { readFileSync } from "node:fs";
import { FACTS as claudeCodeFacts } from "./claude-code.mjs";
import { SECURITY_STAGES, STAGES, SUPPORT_LEVELS, SUPPORT_TABLE } from "./support-levels.mjs";

export { SECURITY_STAGES, STAGES, SUPPORT_LEVELS };

/** Each built-in harness that has an adapter, and its facts. */
const ADAPTERS = { "claude-code": claudeCodeFacts };

const COMMENT =
  "Generated by scripts/gen_harnesses.mjs from cli/src/harness/: do not edit. The shape is grow-only: a field may be added, and is never renamed or removed.";

/**
 * @typedef {{ level: string | null, run: string | null }} Cell
 * @typedef {{
 *   displayName: string,
 *   secrets: Array<{ name: string, whereToGet: string }>,
 *   effortValues: string[],
 *   noEffort: boolean,
 *   defaultModel: string,
 *   supportLevels: Record<string, Cell>,
 * }} Harness
 * @typedef {{ $comment: string, stages: string[], harnesses: Record<string, Harness> }} Harnesses
 */

/**
 * The content of `harnesses.json`, from the adapters and the table.
 * @returns {Harnesses}
 */
export function buildHarnesses() {
  const harnesses = Object.entries(ADAPTERS).map(([name, facts]) => [
    name,
    {
      displayName: facts.displayName,
      secrets: facts.secrets,
      effortValues: facts.effortValues,
      noEffort: facts.effortValues.length === 0,
      defaultModel: facts.defaultModel,
      supportLevels: SUPPORT_TABLE[name],
    },
  ]);
  return structuredClone({
    $comment: COMMENT,
    stages: STAGES,
    harnesses: Object.fromEntries(harnesses),
  });
}

/**
 * The shipped `harnesses.json`: what preflight goes by.
 * @returns {Harnesses}
 */
export function readHarnesses() {
  return JSON.parse(readFileSync(new URL("../../harnesses.json", import.meta.url), "utf8"));
}

/** `a, b or c`. */
const either = (words) =>
  words.length > 1 ? `${words.slice(0, -1).join(", ")} or ${words.at(-1)}` : words.join("");

/**
 * The effort a Stage runs with on `harness` (ADR 0027). Its own setting must
 * be one the harness accepts; one `inherited` from `AGENT_KIT_EFFORT` that is
 * not is dropped, so one global does not break a mixed setup. The refused
 * value is never repeated.
 * @param {Pick<Harness, "displayName" | "effortValues" | "noEffort">} harness
 * @param {{ effort?: string, inherited?: boolean }} setting
 * @returns {{ effort: string, log?: string } | { refused: string }}
 */
export function effortFor(harness, { effort = "", inherited = false }) {
  if (effort === "" || harness.effortValues.includes(effort)) return { effort };
  const why = harness.noEffort
    ? `${harness.displayName} has no effort setting`
    : `${harness.displayName} accepts ${either(harness.effortValues)}`;
  if (inherited) {
    return { effort: "", log: `Effort: AGENT_KIT_EFFORT is dropped for this Stage: ${why}.` };
  }
  return { refused: `${why}, and this Stage's effort is none of that.` };
}

/**
 * Whether `stage` may run on `harness` at its pair's Support Level (ADR 0028),
 * and what the run summary says about it. A security Stage below `tried` runs
 * only as a Proving run; any other Stage runs at `documented` with a warning;
 * a pair with no level is refused.
 * @param {Pick<Harness, "displayName" | "supportLevels">} harness
 * @param {{ stage: string, provingRun?: boolean }} run
 * @returns {{ level?: string, summary?: string, warning?: string, refused?: string }}
 */
export function supportFor(harness, { stage, provingRun = false }) {
  const pair = `${harness.displayName} on the ${stage} Stage`;
  const level = harness.supportLevels[stage]?.level ?? null;
  if (level === null || !SUPPORT_LEVELS.includes(level)) {
    return {
      refused: `${pair} has no Support Level: a Guard probe failed on it, so the pair is refused.`,
    };
  }
  const below = level === "documented";
  if (below && SECURITY_STAGES.includes(stage) && !provingRun) {
    return {
      refused: `${pair} is at Support Level documented, below tried, and a security Stage runs there only as a Proving run (--proving-run).`,
    };
  }
  return {
    level,
    summary: `Support Level: ${level}; Proving run: ${provingRun ? "yes" : "no"}`,
    ...(below
      ? { warning: `${pair} is at Support Level documented: no run of it has been recorded.` }
      : {}),
  };
}
